using System.Windows;
using System.Windows.Controls;
using System.Windows.Media;
using System.Windows.Shapes;
using Kobold.Core;

namespace Kobold.Controls.IconRenderers
{
    /// <summary>
    /// Hand-drawn folder style. The wobble is baked into the fixed path data
    /// (a deterministic offline generator with a set seed); there is no
    /// runtime random and no SVG filter. The paths live directly in the 64x64
    /// tile canvas, scaled and centred to match <see cref="ClassicIconRenderer"/>.
    /// </summary>
    public class HandDrawnIconRenderer : IconRendererBase
    {
        // Generated by the throwaway script (%TEMP%\task-3.3-gen-handdrawn.ps1,
        // seed 20261009, anchors wobbled +-2, controls +-1.5, long lines split
        // into 2-3 segments, then scaled 200 -> 64 with scale 0.43).
        private const string BackPath =
            "M 8.83,14.08 Q 8.56,8.89 13.15,9.84 L 21.8,8.97 L 29.61,8.66 Q 34.43,10 36.69,14.31 L 46.55,14.32 L 56.33,14.19 Q 59.99,13.57 60.67,17.59 L 60.59,28.2 L 60.35,37.88 L 59.86,48.13 Q 60.29,53.03 55.35,52.15 L 40.48,52.26 L 25.42,51.58 L 10.49,51.87 Q 6.76,52.78 5.71,47.71 L 5.91,37.57 L 5.35,27.66 L 5.72,18.06 Q 6.43,14.1 8.83,14.08 Z";
        private const string FrontPath =
            "M 3.33,22.79 Q 4.64,18.41 8.35,17.72 L 24.07,17.97 L 39.17,17.28 L 55.16,17.42 Q 60.67,17.59 59.05,22.29 L 59.57,31.61 L 60.43,40.73 L 60.49,50.54 Q 60.16,54.87 56.12,54.67 L 39.71,55.06 L 24.64,55.25 L 8.25,54.94 Q 4.28,55.06 4.51,50.17 Z";
        private const string HighlightPath =
            "M 9.04,24.92 Q 10.28,22.41 15.26,21.84";
        private static readonly string[] PaperLines =
        {
            "M 9.9,29.1 L 22.85,29.23 L 36.17,28.88 L 49.14,29.04",
            "M 10.53,35.45 L 21.41,35.2 L 32.89,35.4 L 44.41,35.3",
            "M 10.58,41.18 L 19.26,41.09 L 28.07,41.51 L 36.52,41.85"
        };

        public override void Render(Canvas canvas, string color)
        {
            InitColors(color);

            var inkBrush = new SolidColorBrush(InkColor());
            var backBrush = new SolidColorBrush(Utils.MixColor(BaseColor, Colors.White, 0.72));

            canvas.Children.Add(CreatePath(Geometry.Parse(BackPath), backBrush, inkBrush, 2.0));
            canvas.Children.Add(CreatePath(Geometry.Parse(FrontPath), new SolidColorBrush(BaseColor), inkBrush, 2.0));

            var highlight = CreatePath(Geometry.Parse(HighlightPath), null,
                new SolidColorBrush(Color.FromArgb(0x99, 255, 255, 255)), 1.5);
            canvas.Children.Add(highlight);

            foreach (string line in PaperLines)
            {
                canvas.Children.Add(CreatePath(Geometry.Parse(line), null, inkBrush, 1.5));
            }
        }

        /// <summary>
        /// Outline / paper-line ink: a dark variant of the widget colour in the
        /// light theme, a readable light variant on the dark theme, and the
        /// system window text colour under high contrast.
        /// </summary>
        private Color InkColor()
        {
            if (ThemeManager.IsHighContrast) return SystemColors.WindowTextColor;
            return ThemeManager.IsDarkTheme
                ? Utils.LightenColor(BaseColor, 0.55)
                : DarkerColor;
        }

        private static Path CreatePath(Geometry geometry, Brush fill, Brush stroke, double thickness)
        {
            return new Path
            {
                Data = geometry,
                Fill = fill,
                Stroke = stroke,
                StrokeThickness = thickness,
                StrokeLineJoin = PenLineJoin.Round,
                StrokeStartLineCap = PenLineCap.Round,
                StrokeEndLineCap = PenLineCap.Round
            };
        }
    }
}
